"""SQLAlchemy models for ProxyProof."""
from datetime import datetime, timezone
from uuid import uuid4

from sqlalchemy import (
    Boolean,
    DateTime,
    ForeignKey,
    Integer,
    String,
    UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from .database import Base


def utc_now_naive() -> datetime:
    """Return UTC as a naive datetime for consistent SQLite storage."""
    return datetime.now(timezone.utc).replace(tzinfo=None)


class User(Base):
    __tablename__ = "users"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    username: Mapped[str] = mapped_column(String(64), unique=True, index=True, nullable=False)
    display_name: Mapped[str] = mapped_column(String(120), nullable=False)
    password_hash: Mapped[str] = mapped_column(String(256), nullable=False)
    role: Mapped[str] = mapped_column(String(16), default="student", nullable=False)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=utc_now_naive, nullable=False)


class ApiToken(Base):
    __tablename__ = "api_tokens"

    # Store only a digest of the bearer token, never the raw credential.
    token_hash: Mapped[str] = mapped_column(String(64), primary_key=True)
    user_id: Mapped[int] = mapped_column(ForeignKey("users.id"), nullable=False, index=True)
    expires_at: Mapped[datetime] = mapped_column(DateTime, nullable=False, index=True)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=utc_now_naive, nullable=False)


class Device(Base):
    __tablename__ = "devices"
    __table_args__ = (
        UniqueConstraint("user_id", name="uq_device_one_per_user"),
        UniqueConstraint("device_key", name="uq_device_key"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    user_id: Mapped[int] = mapped_column(ForeignKey("users.id"), nullable=False, index=True)
    # Random installation UUID generated by the client. This is device binding,
    # not hardware-backed attestation; document that limitation in the UI.
    device_key: Mapped[str] = mapped_column(String(128), nullable=False)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    registered_at: Mapped[datetime] = mapped_column(DateTime, default=utc_now_naive, nullable=False)


class Room(Base):
    __tablename__ = "rooms"
    __table_args__ = (UniqueConstraint("building", "room_code", name="uq_room_building_code"),)

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    building: Mapped[str] = mapped_column(String(80), nullable=False)
    room_code: Mapped[str] = mapped_column(String(40), nullable=False)
    display_name: Mapped[str] = mapped_column(String(120), nullable=False)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=utc_now_naive, nullable=False)

    sessions: Mapped[list["AttendanceSession"]] = relationship(back_populates="room")


class RoomEnrollment(Base):
    __tablename__ = "room_enrollments"
    __table_args__ = (
        UniqueConstraint("user_id", "room_id", name="uq_room_enrollment_user_room"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    user_id: Mapped[int] = mapped_column(ForeignKey("users.id"), nullable=False, index=True)
    room_id: Mapped[int] = mapped_column(ForeignKey("rooms.id"), nullable=False, index=True)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=utc_now_naive, nullable=False)


class AttendanceSession(Base):
    __tablename__ = "attendance_sessions"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=lambda: str(uuid4()))
    room_id: Mapped[int] = mapped_column(ForeignKey("rooms.id"), nullable=False, index=True)
    # Nullable only for rows created by the pre-ownership prototype; new sessions
    # always record an organiser owner. Legacy ownerless rows are not modifiable.
    created_by_user_id: Mapped[int | None] = mapped_column(
        ForeignKey("users.id"), nullable=True, index=True
    )
    subject_label: Mapped[str] = mapped_column(String(120), nullable=False)
    scheduled_start_at: Mapped[datetime] = mapped_column(DateTime, nullable=False)
    attendance_deadline: Mapped[datetime] = mapped_column(DateTime, nullable=False)
    status: Mapped[str] = mapped_column(String(16), default="open", nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=utc_now_naive, nullable=False)

    room: Mapped[Room] = relationship(back_populates="sessions")


class SessionBleTag(Base):
    __tablename__ = "session_ble_tags"

    session_id: Mapped[str] = mapped_column(
        ForeignKey("attendance_sessions.id"), primary_key=True
    )
    # Six random bytes expressed as 12 hexadecimal characters, compact enough
    # to broadcast in a legacy BLE advertisement together with an 8-byte token.
    tag: Mapped[str] = mapped_column(String(12), unique=True, index=True, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=utc_now_naive, nullable=False)


class AttendanceRecord(Base):
    __tablename__ = "attendance_records"
    __table_args__ = (
        UniqueConstraint("session_id", "student_id", name="uq_attendance_once_per_session"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    session_id: Mapped[str] = mapped_column(
        ForeignKey("attendance_sessions.id"), nullable=False, index=True
    )
    student_id: Mapped[int] = mapped_column(ForeignKey("users.id"), nullable=False, index=True)
    device_id: Mapped[int | None] = mapped_column(ForeignKey("devices.id"), nullable=True)
    marked_at: Mapped[datetime] = mapped_column(DateTime, default=utc_now_naive, nullable=False)
    method: Mapped[str] = mapped_column(String(16), nullable=False)
    rssi_at_mark: Mapped[int | None] = mapped_column(Integer, nullable=True)
    status: Mapped[str] = mapped_column(String(16), default="present", nullable=False)
